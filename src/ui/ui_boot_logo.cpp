// Deterministic per-pixel pseudo-random value (0-255) for the dithered
// fade-in — same (x, y) always hashes to the same value, so the reveal order
// is stable across frames (no flicker) instead of re-randomizing each draw.
uint8_t DitherThreshold(int x, int y)
{
    uint32_t h = static_cast<uint32_t>(x) * 374761393u + static_cast<uint32_t>(y) * 668265263u;
    h = (h ^ (h >> 13)) * 1274126177u;
    h ^= (h >> 16);
    return static_cast<uint8_t>(h & 0xFF);
}
