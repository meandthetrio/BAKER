void DrawRetro(OledPager& display, float progress)
{
    if(progress < 0.0f)
        progress = 0.0f;
    if(progress > 1.0f)
        progress = 1.0f;
    const uint8_t threshold = static_cast<uint8_t>(progress * 255.0f + 0.5f);

    const int stride = (kRetroWidth + 7) / 8;
    for(int row = 0; row < kRetroHeight; ++row)
    {
        const uint8_t* line = kRetroBitmap + (row * stride);
        for(int col = 0; col < kRetroWidth; ++col)
        {
            const uint8_t byte = line[col >> 3];
            const int bit = 7 - (col & 7);
            const bool src_on = ((byte >> bit) & 0x1) != 0;
            if(!src_on && DitherThreshold(col, row) <= threshold)
                display.DrawPixel(col, row, true);
        }
    }
}
