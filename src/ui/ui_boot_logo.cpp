void DrawRetro(OledPager& display)
{
    const int stride = (kRetroWidth + 7) / 8;
    for(int row = 0; row < kRetroHeight; ++row)
    {
        const uint8_t* line = kRetroBitmap + (row * stride);
        for(int col = 0; col < kRetroWidth; ++col)
        {
            const uint8_t byte = line[col >> 3];
            const int bit = 7 - (col & 7);
            const bool src_on = ((byte >> bit) & 0x1) != 0;
            if(!src_on)
                display.DrawPixel(col, row, true);
        }
    }
}

void Draw(OledPager& display)
{
    const int stride = (kLogoWidth + 7) / 8;
    const int x = (static_cast<int>(display.Width()) - kLogoWidth) / 2;
    const int y = (static_cast<int>(display.Height()) - kLogoHeight) / 2;
    for(int row = 0; row < kLogoHeight; ++row)
    {
        const uint8_t* line = kLogoBitmap + (row * stride);
        for(int col = 0; col < kLogoWidth; ++col)
        {
            const uint8_t byte = line[col >> 3];
            const int bit = 7 - (col & 7);
            const bool src_on = ((byte >> bit) & 0x1) != 0;
            if(!src_on)
                display.DrawPixel(x + col, y + row, true);
        }
    }
}
