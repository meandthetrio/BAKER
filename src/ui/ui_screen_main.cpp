static void DrawMainMenuFriendStyle(OledPager& d, int selected)
{
    constexpr int kDisplayW = 128;
    constexpr int kDisplayH = 64;
    constexpr int kListLeftX = 2;
    constexpr int kListGapY = 6;

    d.Fill(false);

    const int text_h = Font5x7::H;
    int max_label_w = 0;
    for(int32_t i = 0; i < kMainMenuCount; ++i)
    {
        const int w = TinyStringWidth(kMenuLabels[i]);
        if(w > max_label_w)
            max_label_w = w;
    }
    const int total_h = (kMainMenuCount * text_h) + ((kMainMenuCount - 1) * kListGapY);
    const int start_y = (kDisplayH - total_h) / 2;
    const int list_w = max_label_w;
    const int icon_area_x = list_w + 4;
    const int icon_area_w = kDisplayW - icon_area_x;

    for(int32_t i = 0; i < kMainMenuCount; ++i)
    {
        const bool is_selected = (i == selected);
        const char* label = kMenuLabels[i];
        const int text_x = kListLeftX;
        const int text_y = start_y + i * (text_h + kListGapY);
        if(is_selected)
        {
            DrawRencFocusTinyString(d, label, text_x, text_y);
        }
        else
        {
            DrawTinyString(d, label, text_x, text_y, true);
        }

        if(is_selected)
        {
            const uint8_t* icon = nullptr;
            int icon_w = 0;
            int icon_h = 0;
            int icon_stride = 0;
            if(i == 0)
            {
                icon = kIconLoadDisk61x29;
                icon_w = kIconW;
                icon_h = kIconH;
                icon_stride = kIconStride;
            }
            else if(i == 1)
            {
                icon = kIconRecordTape61x29;
                icon_w = kIconW;
                icon_h = kIconH;
                icon_stride = kIconStride;
            }
            else if(i == 2)
            {
                icon = kIconPerformMpc61x29;
                icon_w = kIconW;
                icon_h = kIconH;
                icon_stride = kIconStride;
            }
            if(icon != nullptr && icon_area_w > icon_w)
            {
                const int icon_x = icon_area_x + (icon_area_w - icon_w) / 2;
                const int icon_y = (kDisplayH - icon_h) / 2;
                DrawBitmap1bpp(d, icon_x, icon_y, icon_w, icon_h, icon_stride, icon, true);
            }
        }
    }
}

bool MainMenu_OnEvent(UiScreenCtx& ctx, const UiInputEvent& e)
{
    if(!ctx.ui)
        return false;
    if(ctx.shift)
        return false;

    if(e.type == UiInputType::EncDelta && e.id == kUiEncPod && e.value != 0)
    {
        const int32_t next = NextMenuIndex(static_cast<int32_t>(ctx.ui->main_menu_index), e.value);
        ctx.ui->main_menu_index = static_cast<uint8_t>(next);
        ctx.ui->ui_dirty = true;
        return true;
    }

    return false;
}

bool MainMenu_OnEnter(UiScreenCtx& ctx)
{
    if(!ctx.ui)
        return false;

    const uint8_t selected = static_cast<uint8_t>(ctx.ui->main_menu_index % kMainMenuCount);
    switch(selected)
    {
        case 0:
            return UiNav_Push(ctx.ui->ui_nav, UiScreenId::Presets);
        case 1:
            return UiNav_Push(ctx.ui->ui_nav, UiScreenId::Record);
        case 2:
        default:
            return UiNav_Push(ctx.ui->ui_nav, UiScreenId::PerformMenu);
    }
}

void MainMenu_Render(UiScreenCtx& ctx)
{
    if(!ctx.ui || !ctx.display)
        return;

    const int selected = static_cast<int>(ctx.ui->main_menu_index % kMainMenuCount);
    DrawMainMenuFriendStyle(*ctx.display, selected);
}

bool Presets_OnEvent(UiScreenCtx& ctx, const UiInputEvent& e)
{
    if(!ctx.ui || !ctx.project || !ctx.worker)
        return false;

    if(e.type == UiInputType::EncDelta && e.id == kUiEncPod && e.value != 0)
    {
        AppProjectState& project = *ctx.project;
        const int next = static_cast<int>(project.current_project_slot) + e.value;
        project.current_project_slot = ProjectActions_WrapSlot(next);
        ctx.ui->ui_dirty = true;
        return true;
    }

    if(e.type == UiInputType::BtnDown && e.id == kUiBtnExtEnc)
    {
        return ProjectActions_TriggerRequest(*ctx.ui,
                                             *ctx.project,
                                             *ctx.worker,
                                             UiReqType::LoadProject,
                                             ctx.project->current_project_slot);
    }

    // Do not consume BACK events; let the router/nav handle it.
    return false;
}

void Presets_Render(UiScreenCtx& ctx)
{
    if(!ctx.ui || !ctx.project || !ctx.display)
        return;

    AppProjectState& project = *ctx.project;
    OledPager& d = *ctx.display;
    d.Fill(false);

    const uint8_t visible_rows = kPresetsVisibleRows;
    if(visible_rows == 0u)
        return;

    static constexpr int kRowPitch = Font5x7::H + 2;
    const int total_h = static_cast<int>(visible_rows) * Font5x7::H
                        + static_cast<int>(visible_rows - 1u) * 2;
    const int start_y = (static_cast<int>(d.Height()) - total_h) / 2;

    uint8_t top_row = 0;
    if(project.current_project_slot >= visible_rows)
        top_row = static_cast<uint8_t>(project.current_project_slot - (visible_rows - 1u));
    const uint8_t max_top = static_cast<uint8_t>(kProjectSlotCount - visible_rows);
    if(top_row > max_top)
        top_row = max_top;

    for(uint8_t row = 0; row < visible_rows; ++row)
    {
        const uint8_t slot = static_cast<uint8_t>(top_row + row);
        if(slot >= kProjectSlotCount)
            break;

        char label[16];
        std::snprintf(label, sizeof(label), "PROJECT %02u", static_cast<unsigned>(slot + 1u));

        const int row_y = start_y + static_cast<int>(row) * kRowPitch;
        const bool focused = (slot == project.current_project_slot);
        if(focused)
        {
            DrawRencFocusTinyString(d, label, 1, row_y);
        }
        else
        {
            DrawTinyString(d, label, 1, row_y, true);
        }
    }
}
